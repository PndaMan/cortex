export function normalizeLanguage(value: unknown): Language {
  if (value === "zh-CN" || value === "zh" || value === "zh-Hans") return "zh-CN";
  return "en";
}

export function translateText(text: string, language: Language): string {
  if (language === "en" || !text) return text;
  const parts = /^(\s*)([\s\S]*?)(\s*)$/.exec(text);
  if (!parts) return text;
  const [, leading, source, trailing] = parts;
  if (!source) return text;

  const exact = ZH_CN[source];
  if (exact !== undefined) return leading + exact + trailing;

  for (const [pattern, render] of ZH_DYNAMIC) {
    const match = pattern.exec(source);
    if (match) return leading + render(...match.slice(1)) + trailing;
  }
  return text;
}

function cachedLanguage(): Language {
  try {
    if (typeof localStorage !== "undefined") {
      return normalizeLanguage(localStorage.getItem(CACHE_KEY));
    }
  } catch { /* storage unavailable */ }
  return "en";
}

let activeLanguage: Language = cachedLanguage();

export function getLanguage(): Language {
  return activeLanguage;
}

type CopyRecord = { source: string; rendered: string };
const textCopy = new WeakMap<Text, CopyRecord>();
const attributeCopy = new WeakMap<Element, Map<string, CopyRecord>>();
const TRANSLATED_ATTRIBUTES = ["title", "placeholder", "aria-label"] as const;
const SKIP_SELECTOR = [
  "script", "style", "code", "pre", "textarea", "[contenteditable='true']",
  "[data-i18n-skip]", ".rich-text", ".md-body", ".source-content",
  ".s-name", ".t-name", ".src-name", ".note-title", ".note-editor",
  ".subj-name", ".gm-topic-name", ".gm-src-name", ".mat-title", ".an-pill",
  ".sv-name", ".sv-text", ".st-name", ".stl-name", ".cit-ck-label", ".sp-name",
].join(",");

function shouldSkip(element: Element | null): boolean {
  return !!element?.closest(SKIP_SELECTOR);
}

function renderTextNode(node: Text): void {
  if (shouldSkip(node.parentElement)) return;
  const current = node.data;
  let record = textCopy.get(node);
  if (!record) {
    record = { source: current, rendered: current };
    textCopy.set(node, record);
  } else if (current !== record.rendered) {
    // Svelte changed this node (for example a count or status). Treat the new value
    // as the English source; observer callbacks from our own write equal rendered.
    record.source = current;
  }
  const rendered = translateText(record.source, activeLanguage);
  record.rendered = rendered;
  if (current !== rendered) node.data = rendered;
}

function renderAttribute(element: Element, name: string): void {
  if (shouldSkip(element)) return;
  const current = element.getAttribute(name);
  if (current === null) return;
  let records = attributeCopy.get(element);
  if (!records) {
    records = new Map();
    attributeCopy.set(element, records);
  }
  let record = records.get(name);
  if (!record) {
    record = { source: current, rendered: current };
    records.set(name, record);
  } else if (current !== record.rendered) {
    record.source = current;
  }
  const rendered = translateText(record.source, activeLanguage);
  record.rendered = rendered;
  if (current !== rendered) element.setAttribute(name, rendered);
}

function translateElement(element: Element): void {
  for (const name of TRANSLATED_ATTRIBUTES) renderAttribute(element, name);
}

function translateTree(root: Node): void {
  if (root instanceof Text) {
    renderTextNode(root);
    return;
  }
  if (!(root instanceof Element) && !(root instanceof DocumentFragment) && !(root instanceof Document)) return;
  if (root instanceof Element) translateElement(root);

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
  );
  let node = walker.nextNode();
  while (node) {
    if (node instanceof Text) renderTextNode(node);
    else if (node instanceof Element) translateElement(node);
    node = walker.nextNode();
  }
}

let observer: MutationObserver | null = null;
let observedRoot: Node | null = null;

export function applyLanguage(value: unknown): Language {
  activeLanguage = normalizeLanguage(value);
  if (typeof document !== "undefined") {
    document.documentElement.lang = activeLanguage;
    document.documentElement.setAttribute("data-language", activeLanguage);
    if (observedRoot) translateTree(observedRoot);
  }
  try {
    if (typeof localStorage !== "undefined") localStorage.setItem(CACHE_KEY, activeLanguage);
  } catch { /* storage unavailable */ }
  return activeLanguage;
}

export function installDomLocalization(root: Node = document.body): () => void {
  observer?.disconnect();
  observedRoot = root;
  translateTree(root);
  observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData" && mutation.target instanceof Text) {
        renderTextNode(mutation.target);
      } else if (mutation.type === "attributes" && mutation.target instanceof Element && mutation.attributeName) {
        renderAttribute(mutation.target, mutation.attributeName);
      } else if (mutation.type === "childList") {
        for (const node of mutation.addedNodes) translateTree(node);
      }
    }
  });
  observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...TRANSLATED_ATTRIBUTES],
  });
  return () => {
    observer?.disconnect();
    observer = null;
    observedRoot = null;
  };
}

// Called before Svelte mounts so the document language is correct on first paint.
export function bootstrapLanguage(): Language {
  return applyLanguage(activeLanguage);
}
